#!/usr/bin/env python3
"""Generate offline, deterministic vector PDFs and Swift names from vendored Tabler SVGs."""
import argparse
import hashlib
import io
import json
from pathlib import Path
import xml.etree.ElementTree as ET

from reportlab.graphics import renderPDF
from svglib.svglib import svg2rlg

HERE = Path(__file__).resolve().parent
TARGET = HERE.parents[1] / "Packages/IDE/Sources/IconUI"


def outputs():
    manifest = json.loads((HERE / "manifest.json").read_text())
    cases = []
    allowed = {"svg", "path", "circle", "ellipse", "rect", "line", "polyline", "polygon", "g"}
    for icon in manifest["icons"]:
        source = (HERE / "SVG" / (icon["name"] + ".svg")).read_bytes()
        if hashlib.sha256(source).hexdigest() != icon["sha256"]:
            raise ValueError(f"Source checksum changed: {icon['name']}; review and update manifest")
        root = ET.fromstring(source)
        if root.attrib.get("viewBox") != "0 0 24 24":
            raise ValueError("Only 24-point Tabler icons are supported")
        for element in root.iter():
            if element.tag.rsplit("}", 1)[-1] not in allowed:
                raise ValueError(f"Unsupported SVG element: {element.tag}")
            for key, value in element.attrib.items():
                if "href" in key or "url(" in value or key.startswith("on") or key == "style":
                    raise ValueError("External references and SVG CSS are not supported")
                if value == "currentColor":
                    element.set(key, "#000000")
        root.set("stroke-width", str(manifest["strokeWidth"]))
        drawing = svg2rlg(io.BytesIO(ET.tostring(root)))
        if drawing is None or drawing.width != 24 or drawing.height != 24:
            raise ValueError(f"Invalid conversion: {icon['name']}")
        yield TARGET / "Resources" / (icon["name"] + ".pdf"), renderPDF.drawToString(drawing, invariant=1)
        cases.append(f'    case {icon["case"]} = "{icon["name"]}"')
    swift = "// Generated by Tools/Icons/generate.py; edit manifest.json instead.\n"
    swift += "public enum TablerIcon: String, CaseIterable, Sendable {\n" + "\n".join(cases) + "\n}\n"
    yield TARGET / "Generated/TablerIcon.swift", swift.encode()
    yield TARGET / "Resources/Tabler-LICENSE.txt", (HERE / "LICENSE").read_bytes()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify committed outputs without writing")
    args = parser.parse_args()
    mismatches = []
    for path, data in outputs():
        if args.check:
            if not path.exists() or path.read_bytes() != data:
                mismatches.append(str(path.relative_to(HERE.parents[1])))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    if mismatches:
        raise SystemExit("Outdated icon outputs:\n" + "\n".join(mismatches))
    print("Tabler icon outputs verified" if args.check else "Tabler icon outputs generated")


if __name__ == "__main__":
    main()
